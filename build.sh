#!/usr/bin/env bash
# Build the Hackage benchmarks (benchmarks.txt) with the in-tree compiler in
# one configuration:
#
#   ./build.sh NAME "EXTRA GHC OPTIONS"
#
# Every package, the benchmarks and all their dependencies (except the
# compiler's boot packages, as in nofib), is built with -O2 and the options:
# NAME.project (generated) imports cabal.project and sets them for
# 'package *'; cabal hashes them into each package's id, so every
# configuration gets its own builds.  The package store is store/ here, the
# build directory dist-NAME/, the log results/NAME/build.log; extra cabal
# flags (e.g. --keep-going) come from BENCH_CABAL_ARGS.  Dependencies
# come from the local cabal cache (cabal --offline refuses cached
# dependencies, so it is not used; nothing is downloaded while every pinned
# version is cached: setup.sh).  Separate from nofib (ghc-webs/webs-bench/run-nofib.sh).
set -u
# see the resource limits in the memory notes: cap every process.  The large
# group's heaviest modules (pandoc, Agda) need more than 4 GB with the debug
# compiler at -O2: it runs with BENCH_ULIMIT=8000000 BENCH_JOBS=2 inside a
# 16 GB scope, the same total as 4 jobs of 4 GB
ulimit -v "${BENCH_ULIMIT:-4000000}"
cd "$(dirname "$0")"
# BENCH_STORE: another store (relative to here), for another compiler tree
# whose boot packages have the same unit ids (store-xu: ghc-webs/_build-xu)
STORE=$PWD/${BENCH_STORE:-store}
# A benchmark group: a subdirectory with its own benchmarks.txt and
# cabal.project (BENCH_GROUP=large); the store is shared
cd "${BENCH_GROUP:-.}"
NAME=$1
OPTS=${2:-}
mkdir -p "results/$NAME"
# the store, for time.py and trace-apply.py (cabal list-bin)
echo "$STORE" > "results/$NAME/store"
cat > "$NAME.project" <<EOF
-- Generated by build.sh for configuration $NAME
import: cabal.project
package *
  ghc-options: -O2 -rtsopts $OPTS
EOF
# Per-configuration exceptions (package stanzas), appended if present
if [ -f "$NAME.extra" ]; then cat "$NAME.extra" >> "$NAME.project"; fi
# cabal does not notice changes to the imported cabal.project in its plan
# cache: re-plan every time
rm -rf "dist-$NAME/cache"
exes=$(grep -v '^#' benchmarks.txt | awk -F'\t' 'NF >= 3 { print ($2 ~ /:/ ? $2 : "exe:" $2) }' | sort -u | tr '\n' ' ')
cabal --store-dir="$STORE" build -j"${BENCH_JOBS:-4}" ${BENCH_CABAL_ARGS:-} --project-file="$NAME.project" --builddir="dist-$NAME" $exes \
  > "results/$NAME/build.log" 2>&1
status=$?
echo "[$NAME] build exit code: $status" | tee "results/$NAME/exit-code"
grep -n "Downloading" "results/$NAME/build.log" | head -3
grep -n "Lint errors\|panic\|error:" "results/$NAME/build.log" | head -5
exit $status
