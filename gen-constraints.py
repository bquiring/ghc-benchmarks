#!/usr/bin/env python3
"""Write cached.project: a constraint for every package in the local cabal
cache (~/.cabal/packages/hackage.haskell.org) that is not one of the
compiler's boot packages, pinning it to its newest cached version.  The
solver otherwise picks the newest version in the index, which is often not
cached, and cabal --offline then refuses to build.  cabal.project imports
it."""
import os, re, subprocess

CACHE = os.path.expanduser('~/.cabal/packages/hackage.haskell.org')
GHC = os.path.join(os.environ.get('GHC_TREE', os.path.expanduser('~/projects/ghc-webs')), '_build/stage1/bin/ghc')
HERE = os.path.dirname(os.path.abspath(__file__))


def version_key(v):
    return [int(x) for x in re.findall(r'\d+', v)]


libdir = subprocess.run([GHC, '--print-libdir'], capture_output=True, text=True).stdout.strip()
boot = set()
for f in os.listdir(os.path.join(libdir, 'package.conf.d')):
    m = re.match(r'(.+?)-\d[\d.]*(-inplace)?\.conf$', f)
    if m:
        boot.add(m.group(1))

lines = ['-- Generated by gen-constraints.py: the newest cached version of every',
         '-- cached package that is not a boot package of the in-tree compiler.',
         'constraints:']
pins = []
for pkg in sorted(os.listdir(CACHE)):
    d = os.path.join(CACHE, pkg)
    if not os.path.isdir(d) or pkg in boot:
        continue
    vs = [v for v in os.listdir(d)
          if os.path.isfile(os.path.join(d, v, '%s-%s.tar.gz' % (pkg, v)))]
    if vs:
        pins.append('  %s == %s' % (pkg, max(vs, key=version_key)))
lines.append(',\n'.join(pins))
open(os.path.join(HERE, 'cached.project'), 'w').write('\n'.join(lines) + '\n')
print('%d packages pinned, %d boot packages left alone' % (len(pins), len(boot)))
