#!/usr/bin/env python3
"""Regenerate smlbench.cabal and benchmarks.txt from PROGRAMS below:
(benchmark name = SML file name, Haskell module in progs/)."""
import os
PROGRAMS = [
    ('ack', 'Ack'), ('tak', 'Tak'), ('cpstak', 'Cpstak'), ('y-fact', 'YFact'),
    ('nqueens', 'Nqueens'), ('mandelbrot', 'Mandelbrot'), ('quicksort', 'Quicksort'),
    ('filter', 'Filter'), ('derivative', 'Derivative'), ('streams', 'Streams'),
    ('tardis', 'Tardis'), ('interpreter', 'Interpreter'), ('parser-comb', 'ParserComb'),
    ('twenty-four', 'TwentyFour'), ('json-decode', 'JsonDecode'), ('cps-convert', 'CpsConvert'),
    ('knuth-bendix', 'KnuthBendix'), ('raytracer', 'Raytracer'),
    ('ratio-regions', 'RatioRegions'), ('k-cfa', 'KCfa'), ('mc-ray', 'McRay'),
    # higher-order/
    ('defunctionalization', 'Defunctionalization'), ('returned-closures', 'ReturnedClosures'),
    ('function-composition', 'FunctionComposition'), ('mutual-recursion-ho', 'MutualRecursionHo'),
    ('tree-fold-ho', 'TreeFoldHo'), ('curry-uncurry', 'CurryUncurry'),
    ('closure-capture', 'ClosureCapture'), ('higher-order-list', 'HigherOrderList'),
    ('church-encoding', 'ChurchEncoding'), ('cps-explicit', 'CpsExplicit'),
    ('callback-state', 'CallbackState'), ('environment-sharing', 'EnvironmentSharing'),
    ('polymorphic-ho', 'PolymorphicHo'), ('continuation-combinators', 'ContinuationCombinators'),
    ('applicative-functor', 'ApplicativeFunctor'), ('tree-traversal-ho', 'TreeTraversalHo'),
    ('register-allocator', 'RegisterAllocator'), ('dpll-sat', 'DpllSat'),
]
B = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
head = """cabal-version: 2.4
name:          smlbench
version:       0.1
synopsis:      Haskell translations of the 3CPS SML benchmarks
-- Generated by tools/gen.py: one executable per translated program

common prog
  default-language: GHC2021
  build-depends:    base, containers, array, deepseq
  hs-source-dirs:   progs
  other-modules:    Repeat
"""
body = ''.join('\nexecutable %s\n  import:  prog\n  main-is: %s.hs\n' % p for p in PROGRAMS)
open(os.path.join(B, 'smlbench.cabal'), 'w').write(head + body)
open(os.path.join(B, 'benchmarks.txt'), 'w').write(
    '# name\texe\tcommand: each prints what its SML original prints (pass/fail lines)\n'
    + ''.join('%s\tsmlbench:exe:%s\tEXE\n' % (n, n) for n, _ in PROGRAMS))
